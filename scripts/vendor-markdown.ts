// Builds web/vendor/markdown.js: `marked`, minified as one browser IIFE, with a version and licence header. Run it
// after changing the `marked` version with `bun run vendor:markdown`; the file is committed and inlined by src/.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const ENTRY = join(ROOT, "scripts", "markdown-lib.entry.js");
const OUT = join(ROOT, "web", "vendor", "markdown.js");
const HEADER =
  "/*! Markdown renderer bundled for wip web: marked __VERSION__ (MIT, https://github.com/markedjs/marked). " +
  "Generated by `bun run vendor:markdown`; do not edit. */\n";

function main(): void {
  const result = Bun.spawnSync(
    [
      process.execPath,
      "build",
      ENTRY,
      "--minify",
      "--target=browser",
      "--format=iife",
      "--outfile",
      OUT,
    ],
    { cwd: ROOT, stdout: "inherit", stderr: "inherit" },
  );
  if (result.exitCode !== 0) throw new Error(`bun build failed (${result.exitCode})`);
  const marked = JSON.parse(
    readFileSync(join(ROOT, "node_modules", "marked", "package.json"), "utf8"),
  );
  const body = readFileSync(OUT, "utf8");
  writeFileSync(OUT, HEADER.replace("__VERSION__", marked.version as string) + body);
  console.log(`web/vendor/markdown.js · marked ${marked.version} · ${body.length} B`);
}

main();
